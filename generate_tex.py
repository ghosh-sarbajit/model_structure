def safe_name(name):
    return re.sub(r'[^a-zA-Z0-9_-]', '_', name)

def fmt_shape(s):
    return ' × '.join(str(d) for d in s)

def collect_architecture(model):
    layers_info = OrderedDict()
    layer_params_count = {}

    for name, mod in model.named_modules():
        if name == "":
            continue
        children = list(mod.named_children())
        params_list = []
        for pname, param in mod.named_parameters(recurse=False):
            params_list.append({
                "name": pname,
                "shape": list(param.shape),
                "dtype": str(param.dtype).replace("torch.", ""),
                "numel": param.numel(),
            })
        if not children and not params_list:
            continue

        parent = ".".join(name.split(".")[:-1]) if "." in name else ""
        short = name.split(".")[-1]
        typ = type(mod).__name__
        layers_info[name] = {
            "name": name,
            "type": typ,
            "params": params_list,
            "children": [c[0] for c in children],
        }

        n = sum(p.numel() for p in mod.parameters(recurse=False))
        if n > 0:
            layer_params_count[name] = n

    total_params = sum(p.numel() for p in model.parameters())
    return layers_info, layer_params_count, total_params

def generate_tex(model_name, model_path, layers_info, layer_params_count, total_params):
    sn = safe_name(model_name)
    tex = []
    tex.append(r"\documentclass[10pt,a4paper]{article}")
    tex.append(r"\usepackage[utf8]{inputenc}")
    tex.append(r"\usepackage{geometry}")
    tex.append(r"\geometry{margin=0.8in}")
    tex.append(r"\usepackage{booktabs}")
    tex.append(r"\usepackage{longtable}")
    tex.append(r"\usepackage{amsmath,amssymb}")
    tex.append(r"\usepackage{algorithm}")
    tex.append(r"\usepackage{algpseudocode}")
    tex.append(r"\usepackage{xcolor}")
    tex.append(r"\usepackage{hyperref}")
    tex.append("")
    tex.append(r"\title{Model Architecture: " + model_name.replace("_", "\\_") + "}")
    tex.append(r"\author{Generated by sg\_modelload}")
    tex.append(r"\date{\today}")
    tex.append("")
    tex.append(r"\begin{document}")
    tex.append(r"\maketitle")
    tex.append("")

    # -- Summary --
    tex.append(r"\section{Model Overview}")
    tex.append("")
    tex.append(r"\begin{tabular}{ll}")
    tex.append(r"\toprule")
    tex.append(f"  Model Name & {model_name.replace('_', ' ')} \\\\")
    tex.append(f"  Path & {model_path.replace('_', '\\_')} \\\\")
    tex.append(f"  Total Parameters & {total_params:,} \\\\")
    head_dtype = "bfloat16"  # hardcoded as we load in bf16
    tex.append(f"  Weight Dtype & {head_dtype} \\\\")
    tex.append(r"\bottomrule")
    tex.append(r"\end{tabular}")
    tex.append("")

    # -- Architecture Algorithm --
    tex.append(r"\section{Forward Pass Algorithm}")
    tex.append("")
    tex.append(r"\begin{algorithm}[H]")
    tex.append(r"\caption{Forward pass of " + model_name.replace("_", "\\_") + "}")
    tex.append(r"\begin{algorithmic}[1]")

    hidden = None
    for info in layers_info.values():
        if info["type"] == "Embedding":
            for p in info["params"]:
                if p["name"] == "weight":
                    hidden = p["shape"][-1]
                    break
        elif info["type"] in ("LlamaForCausalLM", "Qwen2ForCausalLM",
                            "Qwen3ForCausalLM", "Qwen3_5ForCausalLM",
                            "Gemma3ForConditionalGeneration",
                            "Gemma4ForConditionalGeneration",
                            "GptOssForCausalLM"):
            continue
        elif "lm_head" in info["name"] or info["name"].endswith("lm_head"):
            for p in info["params"]:
                if p["name"] == "weight":
                    vocab = p["shape"][0]
                    break

    if hidden is None:
        for info in layers_info.values():
            if "embed_tokens" in info["name"] or "wte" in info["name"]:
                for p in info["params"]:
                    if p["name"] == "weight":
                        hidden = p["shape"][-1]
                        break

    # Count decoder layers
    n_layers = 0
    if hidden is None:
        for info in layers_info.values():
            if info["type"] in ("LlamaDecoderLayer", "Qwen2DecoderLayer",
                                "Gemma3DecoderLayer", "Gemma4DecoderLayer",
                                "GptOssDecoderLayer"):
                n_layers += 1
                for p in info["params"]:
                    if "input_layernorm" in p["name"] or len(p["shape"]) == 1:
                        hidden = p["shape"][0] if len(p["shape"]) == 1 else hidden
    else:
        layer_keys = [k for k in layers_info if re.search(r'layers?\.\d+', k)]
        unique_layers = set()
        for k in layer_keys:
            m = re.search(r'layers?\.(\d+)', k)
            if m:
                unique_layers.add(int(m.group(1)))
        n_layers = max(unique_layers) + 1 if unique_layers else 0

    # Find vocab size
    vocab_size = None
    for info in layers_info.values():
        if "lm_head" in info["name"] or info["name"] == "lm_head":
            for p in info["params"]:
                if p["name"] == "weight":
                    vocab_size = p["shape"][0]
        elif info["type"] == "Embedding":
            for p in info["params"]:
                if p["name"] == "weight":
                    vocab_size = p["shape"][0]
        if vocab_size:
            break

    # Now generate algorithm
    if hidden:
        tex.append(r"\State $h \gets \text{embed\_tokens}(x) \in \mathbb{R}^{B \times T \times " + str(hidden) + "}$")
    tex.append(r"\For{$layer \gets 0$ \textbf{to} $" + str(n_layers-1) + "$}")
    tex.append(r"\State $h \gets \text{layer}_{layer}(h)$")
    tex.append(r"\EndFor")
    if hidden:
        tex.append(r"\State $h \gets \text{norm}(h) \in \mathbb{R}^{B \times T \times " + str(hidden) + "}$")
    if vocab_size:
        tex.append(r"\State $\text{logits} \gets \text{lm\_head}(h) \in \mathbb{R}^{B \times T \times " + str(vocab_size) + "}$")

    tex.append(r"\end{algorithmic}")
    tex.append(r"\end{algorithm}")

    # -- Layer details --
    tex.append("")
    tex.append(r"\section{Layer-by-Layer Architecture}")
    tex.append("")
    tex.append("All weight tensors and their dimensions are listed below.")
    tex.append("")

    # Determine layer order
    all_keys = list(layers_info.keys())
    # Sort: layers first by index, then other modules
    def sort_key(k):
        m = re.search(r'layers?\.(\d+)', k)
        if m:
            return (0, int(m.group(1)), k)
        return (1, 0, k)
    all_keys.sort(key=sort_key)

    tex.append(r"\begin{longtable}{lllll}")
    tex.append(r"\toprule")
    tex.append(r"Layer Path & Type & Weight Shape & Dtype & Params \\")
    tex.append(r"\midrule")
    tex.append(r"\endfirsthead")
    tex.append(r"\toprule")
    tex.append(r"Layer Path & Type & Weight Shape & Dtype & Params \\")
    tex.append(r"\midrule")
    tex.append(r"\endhead")
    tex.append(r"\midrule \multicolumn{5}{r}{\textit{Continued on next page}} \\")
    tex.append(r"\endfoot")
    tex.append(r"\bottomrule")
    tex.append(r"\endlastfoot")

    for key in all_keys:
        info = layers_info[key]
        display_name = info["name"].replace("_", "\\_")
        typ = info["type"].replace("_", "\\_")
        if info["params"]:
            for p in info["params"]:
                shape_str = " \\times ".join(str(d) for d in p["shape"])
                pname_esc = p['name'].replace("_", "\\_")
                tex.append(f"  {display_name}.{pname_esc} & {typ} & ${shape_str}$ & {p['dtype']} & {p['numel']:,} \\\\")
        elif info["children"]:
            tex.append(f"  {display_name} & {typ} & -- & -- & -- \\\\")

    tex.append(r"\end{longtable}")

    # -- Parameter count estimation --
    tex.append("")
    tex.append(r"\section{Parameter Count Estimation}")
    tex.append("")
    tex.append(r"\begin{tabular}{lrr}")
    tex.append(r"\toprule")
    tex.append(r"Component & Parameters & \% of Total \\")
    tex.append(r"\midrule")

    # Group by component
    component_params = {}
    for key, cnt in layer_params_count.items():
        if "embed_tokens" in key or "wte" in key:
            comp = "Embedding"
        elif "lm_head" in key:
            comp = "LM Head"
        elif "self_attn" in key:
            comp = "Attention"
        elif "mlp" in key:
            comp = "MLP"
        elif "norm" in key or "layernorm" in key or "rmsnorm" in key.lower():
            comp = "LayerNorm"
        elif "rotary" in key:
            comp = "Rotary Embedding"
        else:
            comp = "Other"
        component_params[comp] = component_params.get(comp, 0) + cnt

    for comp, cnt in sorted(component_params.items(), key=lambda x: -x[1]):
        pct = cnt / total_params * 100
        tex.append(f"  {comp} & {cnt:,} & {pct:.1f}\\% \\\\")

    tex.append(r"\midrule")
    tex.append(f"  \\textbf{{Total}} & \\textbf{{{total_params:,}}} & \\textbf{{100.0\\%}} \\\\")
    tex.append(r"\bottomrule")
    tex.append(r"\end{tabular}")
    tex.append("")

    # Layer-by-layer param count
    tex.append("")
    tex.append(r"\subsection{Per-Layer Parameter Count}")
    tex.append("")
    tex.append(r"\begin{tabular}{lrr}")
    tex.append(r"\toprule")
    tex.append(r"Layer & Params & Running Total \\")
    tex.append(r"\midrule")
    running = 0
    for key in all_keys:
        if key in layer_params_count:
            cnt = layer_params_count[key]
            running += cnt
            display = key.replace("_", "\\_")
            tex.append(f"  {display} & {cnt:,} & {running:,} \\\\")
    tex.append(r"\bottomrule")
    tex.append(r"\end{tabular}")

    tex.append("")
    tex.append(r"\end{document}")

    tex_path = os.path.join(OUT_DIR, f"{sn}.tex")
    with open(tex_path, "w") as f:
        f.write("\n".join(tex) + "\n")
    print(f"  Written: {tex_path}")
    return tex_path

for model_name, model_path in models_info:
    sn = safe_name(model_name)
    print(f"\n{'='*60}")
    print(f"Analyzing: {model_name}")
    print('='*60)
    try:
        tokenizer = AutoTokenizer.from_pretrained(model_path, trust_remote_code=True)
        model = AutoModelForCausalLM.from_pretrained(
            model_path, trust_remote_code=True, torch_dtype=torch.bfloat16
        )
        model = model.to("cuda")
        layers_info, layer_params_count, total_params = collect_architecture(model)
        generate_tex(model_name, model_path, layers_info, layer_params_count, total_params)
        del model, tokenizer
        torch.cuda.empty_cache()
    except Exception as e:
        print(f"  FAILED: {e}")

print(f"\nAll .tex files saved to {OUT_DIR}/")
